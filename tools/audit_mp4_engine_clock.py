def build_profile(metadata, native, platform):
    from capstone import Cs, CS_ARCH_ARM64, CS_MODE_LITTLE_ENDIAN
    from extract_client_schema import ClientImage
    from audit_mp4_ios_game import Original
    pin, size = PINS[platform]
    assert len(native) == size and hashlib.sha256(native).hexdigest() == pin, "original_engine_pin_mismatch"
    image = ClientImage(metadata, native) if platform == "android" else Original(metadata, native)
    offset = image.file_offset if platform == "android" else image.offset
    disassembler = Cs(CS_ARCH_ARM64, CS_MODE_LITTLE_ENDIAN)

    def raw(address, size):
        return native[offset(address):offset(address) + size]

    def code(address, size):
        return list(disassembler.disasm(raw(address, size), address))

    bindings = {name: {"rva": hex(address), "prefix": raw(address, 16).hex(),
        "body": raw(address, size).hex(), "bytes": size} for name, (address, size) in METHODS[platform].items()}
    getters = {}
    for name, (entry, load, register, field) in GETTERS[platform].items():
        instruction = code(load, 4)[0]
        assert instruction.mnemonic == "ldr" and instruction.op_str == f"{register}, [x0, #{hex(field)}]"
        getters[name] = {"rva": hex(entry), "load_rva": hex(load), "load": instruction.bytes.hex(), "field": field, "register": register}
    update = code(*METHODS[platform]["update"])
    for name in ("fixed_work", "fixed_tick", "fixed_cache_refresh", "level_reset"):
        assert code(*METHODS[platform][name])[-1].mnemonic == "ret", "clock_method_boundary_differs"
    cache = [(row.mnemonic, row.op_str) for row in code(*METHODS[platform]["fixed_cache_refresh"])]
    assert ("ldr", "s0, [x0, #0x48]") in cache
    assert ("str", "s1, [x0, #0x58]") in cache and ("str", "s0, [x0, #0x50]") in cache
    assert not any(row.mnemonic in {"bl", "blr"} for row in update), "clock_kernel_contains_unknown_calls"
    assert any(row.mnemonic == "ldr" and row.op_str.endswith("[x0, #0xd8]") and row.op_str.startswith("s") for row in update)
    assert any(row.mnemonic == "str" and row.op_str.endswith("[x0, #0xc8]") for row in update)
    assert any(row.mnemonic == "str" and row.op_str.endswith("[x0, #0xd0]") for row in update)
    constants, addresses = [], {}
    for row in update:
        parts = row.op_str.split(", ")
        if row.mnemonic == "adrp":
            addresses[parts[0]] = int(parts[1].lstrip("#"), 0)
        elif row.mnemonic == "add" and len(parts) == 3:
            if parts[1] in addresses and parts[2].startswith("#"):
                addresses[parts[0]] = addresses[parts[1]] + int(parts[2][1:], 0)
            else:
                addresses.pop(parts[0], None)
        elif row.mnemonic == "ldr" and len(parts) == 3 and parts[1].startswith("["):
            register = parts[1][1:]
            if register in addresses:
                address = addresses[register] + int(parts[2].rstrip("]").lstrip("#"), 0)
                width = {"s": 4, "d": 8}.get(parts[0][0])
                assert width, "unexpected_native_clock_constant_width"
                constants.append({"rva": hex(address), "bytes": raw(address, width).hex()})
    constants = list({row["rva"]: row for row in constants}.values())
    vtable, registry = (0x14139c8, 0x1497840) if platform == "android" else (0x97ebb78, 0xa85a408)
    pointer = image.relocations[vtable + 0xc0] if platform == "android" else image.qword(vtable + 0xc0)
    assert pointer == METHODS[platform]["update"][0]
    manager_code = code(*METHODS[platform]["get_manager"])
    assert manager_code[0].mnemonic == "mov" and manager_code[0].op_str == "w0, #7"
    registry_getter = int(manager_code[1].op_str.lstrip("#"), 0)
    registry_code = code(registry_getter, 16)
    assert registry_code[0].mnemonic == "adrp" and registry_code[0].op_str.startswith("x8, #")
    assert registry_code[1].mnemonic == "add" and registry_code[1].op_str.startswith("x8, x8, #")
    registry_base = int(registry_code[0].op_str.split("#")[1], 0) + int(registry_code[1].op_str.split("#")[1], 0)
    assert registry_base + 7 * 8 == registry
    assert registry_code[2].mnemonic == "ldr" and registry_code[2].op_str == "x0, [x8, w0, sxtw #3]"
    caller = 0x64b608 if platform == "android" else 0xcd5768
    caller_code = code(caller, 28 if platform == "android" else 32)
    caller_text = [(row.mnemonic, row.op_str) for row in caller_code]
    assert ("bl", "#" + hex(METHODS[platform]["get_manager"][0])) in caller_text
    assert ("ldr", "x1, [x8, #0xc0]") in caller_text and ("mov", "v0.16b, v8.16b") in caller_text
    assert caller_text[-1] == ("br", "x1")
    return {"schema": 1, "platform": platform, "source": {"native_sha256": pin, "native_bytes": size},
        "native_abi": "void(TimeManager*, double nativeWallTimestampInD0)",
        "bindings": bindings, "getters": getters, "kernel_constants": constants,
        "registry_slot_rva": hex(registry), "manager_vtable_rva": hex(vtable), "vtable_update_offset": 0xc0,
        "registry_getter": {"rva": hex(registry_getter), "bytes": raw(registry_getter, 16).hex()},
        "native_update_caller": {"rva": hex(caller), "bytes": raw(caller, len(caller_code) * 4).hex()},
        "layout": {name: {"offset": field, "kind": kind} for name, (field, kind) in LAYOUT.items()},
        "preserve": {"native_frame_counter": {"offset": 0xc8, "kind": "uint64"},
            "native_frame_counter_secondary": {"offset": 0xd0, "kind": "uint32"}, "one_shot_flags": [0xc0, 0xc1, 0xc2], "level_offset_on_new_scene": 0xf0},
        "scope": {"full_playerloop_executed": False, "native_realtime_virtualized": False,
            "particle_physics_culling_closure_proven": False, "fixed_delta_setting_changed": False}}


def render_header(profiles):
    names = tuple(METHODS["android"])
    lines = ["namespace idoly_mp4_engine_clock {", "struct Binding { uintptr_t rva;uint8_t prefix[16]; };",
        "struct Profile {", "    const char* native_sha256;uintptr_t registry_slot,manager_vtable;",
        "    Binding " + ",".join(names) + ";", "};"]
    for platform in ("android", "ios"):
        row = profiles[platform]
        lines += [f"inline constexpr Profile {platform}_profile={{",
            f'    "{row["source"]["native_sha256"]}",{row["registry_slot_rva"]},{row["manager_vtable_rva"]},']
        for name in names:
            method = row["bindings"][name]
            prefix = ",".join(hex(value) for value in bytes.fromhex(method["prefix"]))
            lines += [f'    {{{method["rva"]},{{{prefix}}}}}, // {name}']
        lines += ["};"]
    return "\n".join([*lines, "} // namespace idoly_mp4_engine_clock", ""])


def render_scope_header(profiles, source=None):
    """Keep the generated profile in the compiled scope's source closure."""
    if source is None:
        source = (ROOT / "client-presentation/native/mp4_engine_clock.hpp").read_text()
    begin, end = "// BEGIN_ORIGINAL_ENGINE_CLOCK_PROFILE", "// END_ORIGINAL_ENGINE_CLOCK_PROFILE"
    assert source.count(begin) == source.count(end) == 1, "clock_profile_section_missing"
    generated = begin + "\n" + render_header(profiles).rstrip() + "\n" + end
    return re.sub(re.escape(begin) + r"[\s\S]*?" + re.escape(end), lambda _: generated, source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--originals", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "client-presentation/native")
    args = parser.parse_args()
    profiles = {}
    for platform, meta, native in (("android", "android-metadata.dat", "mp4-android-analysis/libunity.so"), ("ios", "ios-metadata.dat", "ios-native.bin")):
        profiles[platform] = build_profile((args.originals / meta).read_bytes(), (args.originals / native).read_bytes(), platform)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "mp4_engine_clock_profile.json").write_text(json.dumps({"schema": 1, "platforms": profiles}, indent=2) + "\n")
    (args.output_dir / "mp4_engine_clock.hpp").write_text(render_scope_header(profiles))
    print("PASS exact Android+iOS native clock profiles; no full engine execution claim")


if __name__ == "__main__":
    main()
