def need(value, message):
    if not value:
        raise ValueError("renderer_program_" + message)


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def serialized_programs(raw):
    """Return source object identity independent of metadata/object placement."""
    need(isinstance(raw, bytes) and 48 <= len(raw) <= MAX_ASSET, "serialized_size")
    need(struct.unpack_from(">4I", raw) == (0, 0, 22, 0) and raw[16:20] == bytes(4), "serialized_header")
    metadata, size, offset, unknown = struct.unpack_from(">IQQQ", raw, 20)
    need(unknown == 0 and size == len(raw) and 48 <= offset <= MAX_METADATA
         and 0 < metadata <= offset - 48 and offset <= size, "serialized_extent")
    end = 48 + metadata
    at = raw.find(bytes(1), 48, min(end, 128))
    need(at >= 0 and raw[48:at] == b"2022.3.57f1", "unity_version")
    at += 1
    need(at + 9 <= end and struct.unpack_from("<i", raw, at)[0] in (9, 13), "target_platform")
    at += 4
    need(raw[at] == 0, "unstripped_type_tree")
    count = struct.unpack_from("<i", raw, at + 1)[0]
    at += 5
    need(0 < count <= 16384, "type_count")
    types = []
    for _ in range(count):
        need(at + 23 <= end, "type_truncated")
        cls = struct.unpack_from("<i", raw, at)[0]
        length = 39 if cls == 114 else 23
        need(at + length <= end, "type_script_truncated")
        types.append(cls)
        at += length
    need(at + 4 <= end, "object_count_truncated")
    count = struct.unpack_from("<i", raw, at)[0]
    at = (at + 7) & ~3
    need(0 < count <= 500000 and at + 24 * count <= end, "object_table")
    last = None
    spans = []
    programs = {}
    for number in range(count):
        path, relative, length, kind = struct.unpack_from("<qQIi", raw, at + number * 24)
        need((last is None or last < path) and 0 <= kind < len(types)
             and relative <= size - offset and length <= size - offset - relative, "object_extent")
        last = path
        if length:
            spans.append((relative, relative + length))
        if types[kind] in PROGRAM_CLASSES:
            need(0 < length <= MAX_PROGRAM, "object_program_size")
            payload = raw[offset + relative:offset + relative + length]
            programs[str(path)] = {"class_id": types[kind], "bytes": length, "sha256": digest(payload)}
    spans.sort()
    need(all(a[1] <= b[0] for a, b in zip(spans, spans[1:])), "object_overlap")
    return programs


def source_manifest_digest(platform):
    need(platform in PROGRAMS, "platform")
    return digest(json.dumps(PROGRAMS[platform], sort_keys=True, separators=(",", ":")).encode())


def _asset_bytes(archive, prefix, name):
    members = archive.infolist()
    names = [info.filename for info in members]
    need(len(names) <= 16000 and len(set(names)) == len(names), "archive_members")
    path = prefix + name
    chunks = [n for n in names if n.startswith(path + ".split")]
    if chunks:
        need(path not in names and all(re.fullmatch(re.escape(path) + r"\.split\d+", n) for n in chunks), "split_name")
        chunks.sort(key=lambda n: int(n.rsplit(".split", 1)[1]))
        need([int(n.rsplit(".split", 1)[1]) for n in chunks] == list(range(len(chunks))), "split_sequence")
    else:
        need(path in names, "asset_missing:" + name)
        chunks = [path]
    size = 0
    blobs = []
    for n in chunks:
        info = archive.getinfo(n)
        need(not info.is_dir() and not info.flag_bits & 1 and 0 <= info.file_size <= MAX_ASSET, "asset_member")
        size += info.file_size
        need(size <= MAX_ASSET, "asset_total")
        blob = archive.read(n)
        need(len(blob) == info.file_size, "asset_truncated")
        blobs.append(blob)
    return b"".join(blobs)


def verify_archive(path, platform, *, prefix=None):
    need(platform in PROGRAMS, "platform")
    prefix = prefix if prefix is not None else ("assets/bin/Data/" if platform == "android" else "Payload/IDOLY PRIDE.app/Data/")
    checked, count = [], 0
    with ZipFile(path) as archive:
        asset_names = {re.sub(r"\.split\d+$", "", i.filename[len(prefix):])
                       for i in archive.infolist() if i.filename.startswith(prefix)
                       and re.fullmatch(r"[^/]+\.assets(?:\.split\d+)?", i.filename[len(prefix):])}
        for name in sorted(asset_names - PROGRAMS[platform].keys()):
            need(not serialized_programs(_asset_bytes(archive, prefix, name)), "unexpected_program_file:" + name)
        for name, expected in sorted(PROGRAMS[platform].items()):
            actual = serialized_programs(_asset_bytes(archive, prefix, name))
            need(actual == expected, "object_mismatch:" + name)
            count += len(actual)
            checked.append(name)
    return {"schema": 1, "platform": platform, "program_objects": count,
            "serialized_files": checked, "program_manifest_sha256": source_manifest_digest(platform),
            "shader_and_compute_object_bytes_preserved": True,
            "whole_serialized_file_equality_required": False}


def verify_asset_bytes(raw, platform, name):
    need(platform in PROGRAMS and name in PROGRAMS[platform], "asset_role")
    actual = serialized_programs(raw)
    need(actual == PROGRAMS[platform][name], "object_mismatch:" + name)
    return {"program_objects": len(actual), "program_manifest_sha256": source_manifest_digest(platform)}


