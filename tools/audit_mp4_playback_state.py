#!/usr/bin/env python3
"""Derive typed playback-state calls from the two exact original clients.

This generates bindings only. The separate native-director implementation and
actor-job fence audits establish the permitted protocol; no game/GPU is run.
"""
from pathlib import Path
import argparse
import hashlib
import json

from audit_mp4_game import OriginalAndroid
from audit_mp4_ios_game import Original,need

ROOT=Path(__file__).resolve().parents[1]
START="// BEGIN_ORIGINAL_PLAYBACK_PROFILE"
END="// END_ORIGINAL_PLAYBACK_PROFILE"
SELECT={
    "director_state":("UnityEngine.Playables.PlayableDirector","get_state",0),
    "director_play":("UnityEngine.Playables.PlayableDirector","Play",0),
    "director_pause":("UnityEngine.Playables.PlayableDirector","Pause",0),
    "director_resume":("UnityEngine.Playables.PlayableDirector","Resume",0),
    "director_rebuild":("UnityEngine.Playables.PlayableDirector","RebuildGraph",0),
    "player_playing":("Solis.Common.Live.SolisLivePlayerBase","get_IsPlaying",0),
    "player_paused":("Solis.Common.Live.SolisLivePlayerBase","get_IsPause",0),
    "player_set_playing":("Solis.Common.Live.SolisLivePlayerBase","set_IsPlaying",1),
    "player_set_paused":("Solis.Common.Live.SolisLivePlayerBase","set_IsPause",1),
}


def profile(original,platform):
    methods={name:original.method(*value)for name,value in SELECT.items()}
    for method in methods.values():
        args=[]if method["static"]else["void*"]
        args.extend(original.native_type(value["type"])for value in method["parameters"])
        method["native_abi"]=original.native_type(method["return"])+"("+",".join([*args,"const MethodInfo*"])+")"
    fields=original.fields("Solis.Common.Live.SolisLivePlayerBase")
    fields={name:fields[name]for name in ("<Built>k__BackingField","<IsPlaying>k__BackingField","<IsPause>k__BackingField")}
    need([row["offset"]for row in fields.values()]==[0x70,0x71,0x72],"original_playback_flags_differ")
    enums={}
    for alias,owner,name,expected in (("game_time","UnityEngine.Playables.DirectorUpdateMode","GameTime",1),
            ("paused","UnityEngine.Playables.PlayState","Paused",0),("playing","UnityEngine.Playables.PlayState","Playing",1)):
        value,proof=original.enum_value(owner,name);need(value==expected,"original_playback_enum_differs");enums[alias]={"value":value,"proof":proof}
    return {"platform":platform,"sources":{"native_sha256":hashlib.sha256(original.b).hexdigest(),"metadata_sha256":hashlib.sha256(original.m).hexdigest()},
        "methods":methods,"fields":fields,"enums":enums,
        "base_lifecycle_audit":{name:original.method("Solis.Common.Live.SolisLivePlayerBase",name,0)for name in ("Play","Pause","Resume")},
        "scope":{"typed_managed_call_bindings_verified":True,"game_or_gpu_executed":False,
            "automatic_export_permitted_without_verified_dependent_state":False,
            "native_rebuild_and_actor_job_fence_proof_required":True}}


def render(profiles):
    lines=[START,"// Generated by tools/audit_mp4_playback_state.py from exact original clients.",
        "struct Binding { uintptr_t rva;uint8_t prefix[16]; };","struct Profile {"]
    for name in SELECT:lines.append("    Binding "+name+";")
    lines +=["};"]
    for platform in ("android","ios"):
        lines +=["inline constexpr Profile "+platform+"_profile={"]
        for name in SELECT:
            method=profiles[platform]["methods"][name]
            lines.append("    {"+method["rva"]+",{"+",".join("0x"+method["prefix"][i:i+2]for i in range(0,32,2))+"}}, // "+name)
        lines +=["};"]
    lines +=[END]
    return "\n".join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--originals",type=Path,required=True)
    parser.add_argument("--output-dir",type=Path,default=ROOT/"client-presentation/native")
    args=parser.parse_args();profiles={}
    for platform,constructor,metadata,native in (("android",OriginalAndroid,"android-metadata.dat","android-native.so"),("ios",Original,"ios-metadata.dat","ios-native.bin")):
        profiles[platform]=profile(constructor((args.originals/metadata).read_bytes(),(args.originals/native).read_bytes()),platform)
    output=args.output_dir;output.mkdir(parents=True,exist_ok=True)
    (output/"mp4_playback_state_profile.json").write_text(json.dumps({"schema":1,"platforms":profiles},indent=2)+"\n")
    header=output/"mp4_playback_state.hpp"
    source=header.read_text()if header.is_file()else(ROOT/"client-presentation/native/mp4_playback_state.hpp").read_text()
    before,rest=source.split(START,1);_,after=rest.split(END,1)
    header.write_text(before+render(profiles)+after)
    print("PASS exact original playback-state call/field/enum bindings; dependent state and native graph semantics remain separate mandatory proofs")


if __name__=="__main__":main()
