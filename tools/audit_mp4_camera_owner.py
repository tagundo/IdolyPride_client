#!/usr/bin/env python3
"""Recover the exact selected-camera component lookup from pinned originals.

GetComponent is queried only on the output Camera already owned by the selected
MV timeline. This audit establishes ABI/type/field identity; it does not run the
game or assert that any current scene contains that component.
"""
from pathlib import Path
import argparse, hashlib, json
from audit_mp4_game import OriginalAndroid
from audit_mp4_ios_game import Original, need
ROOT=Path(__file__).resolve().parents[1]
START="// BEGIN_MP4_CAMERA_OWNER_PROFILE"
END="// END_MP4_CAMERA_OWNER_PROFILE"
def build_profile(original,platform):
    method=original.method("UnityEngine.Component","GetComponent",1,("System.Type",))
    need(not method["static"] and method["return"]=="UnityEngine.Component","camera_component_signature_differs")
    method["native_abi"]="void*(void*,void*,const MethodInfo*)"
    name="VL.Rendering.VLSRPCameraController"
    tid=original.type_id(name);index=original.types[tid][1][2]
    pointer=original.qword(original.type_table+index*8)
    need(original.type_name(index)==name,"camera_controller_type_differs")
    descriptor={"type":name,"rva":hex(pointer),"prefix":original.b[original.offset(pointer):original.offset(pointer)+16].hex(),"metadata_type_index":index,"metadata_type_definition_index":tid}
    fields={alias:{"owner":owner,"name":field,**original.fields(owner)[field]} for alias,owner,field in (
        ("controller_camera",name,"_mainCamera"),("brain_camera","Cinemachine.CinemachineBrain","m_OutputCamera"),
        ("timeline_output_tracks","UnityEngine.Timeline.TimelineAsset","m_CacheOutputTracks"))}
    need(fields["controller_camera"]["offset"]==0x50 and fields["brain_camera"]["offset"]==0x50,"camera_owner_field_differs")
    need(fields["timeline_output_tracks"]["type"]=="UnityEngine.Timeline.TrackAsset[]","timeline_output_collection_differs")
    return {"schema":1,"platform":platform,"sources":{"native_sha256":hashlib.sha256(original.b).hexdigest(),"metadata_sha256":hashlib.sha256(original.m).hexdigest()},"component_get_component":method,"controller_type":descriptor,"fields":fields,"scope":{"game_executed":False,"runtime_verified":False,"receiver":"Already verified selected timeline CinemachineBrain.OutputCamera only","result":"Must be a live original VLSRPCameraController whose mainCamera is that same Camera","controller_creation":False}}
def render_header(profiles):
    lines=[START,"// Generated by tools/audit_mp4_camera_owner.py from pinned originals.","struct CameraOwnerProfile { Binding component_get_component,controller_type; };"]
    for platform in ("android","ios"):
        lines += ["inline constexpr CameraOwnerProfile "+platform+"_camera_owner_profile={"]
        for name in ("component_get_component","controller_type"):
            row=profiles[platform][name]
            lines += ["    {"+row["rva"]+", {"+", ".join(hex(v) for v in bytes.fromhex(row["prefix"]))+"}}, // "+name]
        lines += ["};"]
    return "\n".join([*lines,END])
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--originals",type=Path,required=True)
    parser.add_argument("--output-dir",type=Path,default=ROOT/"client-presentation/native")
    args=parser.parse_args();profiles={}
    for platform,C,metadata,native in (("android",OriginalAndroid,"android-metadata.dat","android-native.so"),("ios",Original,"ios-metadata.dat","ios-native.bin")):
        profiles[platform]=build_profile(C((args.originals/metadata).read_bytes(),(args.originals/native).read_bytes()),platform)
    (args.output_dir/"mp4_camera_owner_profile.json").write_text(json.dumps({"schema":1,"platforms":profiles},indent=2)+"\n")
    header=args.output_dir/"mp4_controller_profile.hpp";source=header.read_text()
    if START in source:
        before,rest=source.split(START,1);_,after=rest.split(END,1)
    else:
        before,after=source.rsplit("} // namespace idoly_mp4_game",1)
        after="\n} // namespace idoly_mp4_game"+after
    header.write_text(before+render_header(profiles)+after)
    print("PASS exact selected Camera component lookup bindings; no runtime validation")
if __name__=="__main__":main()
